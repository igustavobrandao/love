-- Schema para Postgres (Neon). Execute uma vez no SQL Editor do Neon.
-- Não há RLS: o banco só é acessado pelas funções em /api, com a DATABASE_URL
-- guardada em variável de ambiente no servidor. O navegador nunca fala com o banco.

CREATE TABLE IF NOT EXISTS couple_config (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    couple_name TEXT,
    relationship_start TIMESTAMPTZ,
    background_music_url TEXT,
    custom_phrase TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS photos (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    file_path TEXT NOT NULL,
    public_url TEXT NOT NULL,
    caption TEXT,
    mime_type TEXT,
    size_bytes INTEGER,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS couple_photos (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    couple_config_id BIGINT NOT NULL REFERENCES couple_config(id) ON DELETE CASCADE,
    photo_id BIGINT NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    display_order INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (couple_config_id, photo_id)
);

CREATE INDEX IF NOT EXISTS idx_couple_photos_couple_config_id ON couple_photos(couple_config_id);
CREATE INDEX IF NOT EXISTS idx_couple_photos_photo_id ON couple_photos(photo_id);

-- Controle de tentativas de login (limite por IP)
CREATE TABLE IF NOT EXISTS login_attempts (
    ip TEXT PRIMARY KEY,
    attempts INTEGER NOT NULL DEFAULT 0,
    window_start TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_couple_config_updated_at ON couple_config;
CREATE TRIGGER update_couple_config_updated_at
    BEFORE UPDATE ON couple_config
    FOR EACH ROW EXECUTE PROCEDURE update_updated_at_column();

DROP TRIGGER IF EXISTS update_photos_updated_at ON photos;
CREATE TRIGGER update_photos_updated_at
    BEFORE UPDATE ON photos
    FOR EACH ROW EXECUTE PROCEDURE update_updated_at_column();
